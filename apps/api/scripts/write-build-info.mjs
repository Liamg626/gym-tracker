// Writes src/build-info.ts with the commit SHA of this build. Workers Builds exposes
// WORKERS_CI_COMMIT_SHA; plain CI uses GITHUB_SHA; locally we ask git. Falls back to 'dev'.
import { execSync } from 'node:child_process';
import { writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';

const fromGit = () => {
  try {
    return execSync('git rev-parse HEAD', { stdio: ['ignore', 'pipe', 'ignore'] })
      .toString()
      .trim();
  } catch {
    return '';
  }
};

const sha = process.env.WORKERS_CI_COMMIT_SHA || process.env.GITHUB_SHA || fromGit() || 'dev';
const target = fileURLToPath(new URL('../src/build-info.ts', import.meta.url));
writeFileSync(
  target,
  `// Generated by scripts/write-build-info.mjs. Do not edit; git-ignored.\nexport const BUILD_SHA = ${JSON.stringify(sha)};\n`,
);
console.log(`build-info: ${sha}`);
